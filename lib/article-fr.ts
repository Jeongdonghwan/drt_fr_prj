// 지역 창업 페이지의 긴 안내글 (소제목 5개 · 약 1,500자).
// 사실 근거: 공식 가맹 페이지(핵심 경쟁력·왜 도로시펫·시장 변화·11단계·상담 방법), 동물보호법(동물판매업 허가).
// 넣지 않는 것: 지역 통계·순위, 비용 숫자, 매장 운영 안내(분양 절차·홈딜리버리·미용·호텔).
// 같은 문장이 1,000쪽에 반복되지 않게 문단마다 지역명·유형이 들어간 표현 2~3벌을 두고 슬러그 해시로 고른다.
import { FrWord, hash } from './data';
import { BRAND, CONTACT, FR_MOTTO } from './site';
import { j } from './ko';

const pick = <T,>(arr: T[], s: string, salt: string) => arr[hash(`${s}::${salt}`) % arr.length];
const rotate = <T,>(arr: T[], s: string, salt: string) => arr.map((x, i) => [hash(`${s}::${salt}::${i}`), x] as [number, T]).sort((a, b) => a[0] - b[0]).map((x) => x[1]);

type Sec = { id: string; h: string[]; p: string[][] };

export function articleFr({ s, word, short, L, branch, breakdown }: { s: string; word: FrWord; short: string; L: string; branch?: string; breakdown: boolean }) {
  const where = short === '전국' ? '어느 지역에서든' : `${short}에서`;
  const SECS: Sec[] = [
    { id: 'why', h: [`${where} ${j(L, '을')} 고민한다면`, `${short} ${L}, 왜 지금 업종부터 다시 볼까`, `${short} ${L}을 준비하는 분께`], p: [[
      `${where} ${j(L, '을')} 알아보는 분이 가장 먼저 묻는 것은 '오래 할 수 있는 업종인가'입니다. 인건비와 운영비가 오르고 플랫폼 수수료가 커지면서, 지금 반짝 잘 되는 업종보다 꾸준히 운영할 수 있는 구조가 더 중요해졌습니다.`,
      `요즘 ${short}에서 창업을 준비하는 분들은 예전과 분위기가 달라졌다고 말합니다. 열심히만 하면 된다는 방식으로는 버티기 어렵고, 업종보다 운영 구조를 먼저 따져 보는 흐름입니다.`,
    ], [
      `반려동물 분양은 키오스크나 무인 운영으로 대신하기 어려운 일입니다. 상담과 신뢰, 분양 뒤 소통이 매장의 중심이라 사람의 경험이 그대로 경쟁력이 됩니다. ${BRAND}이 ${short} 예비 점주님께 ${j(L, '을')} 권하는 이유도 여기에 있습니다.`,
      `${L}은 사람이 직접 상담하고 신뢰를 쌓는 업종입니다. 그래서 ${short}에서도 혼자 시스템을 만들기보다, 이미 운영 중인 매장의 방식을 가져오는 편이 시행착오를 줄입니다.`,
    ]] },
    { id: 'hard', h: [`혼자 준비하면 막히는 것`, `${short} ${L}, 처음이라면 어려운 부분`, `개인 창업으로 시작할 때의 부담`], p: [[
      `분양 매장은 해야 할 일이 많습니다. 아이를 들여올 공급처를 찾고, 건강과 개체를 관리하고, 상담·계약·사후관리까지 직접 챙겨야 합니다. ${short}에서 처음 시작하는 분이 이 모든 시스템을 혼자 만들기는 쉽지 않습니다.`,
      `${L}에서 개인이 가장 막히는 곳은 공급망과 관리 체계입니다. 출신이 확실한 켄넬·캐터리를 찾는 일부터 건강 정보 관리, 계약서와 사후관리 응대까지 처음부터 만들려면 시간과 비용이 큽니다.`,
    ], [
      `여기에 동물을 판매하는 영업은 동물보호법에 따라 지자체의 동물판매업 허가를 받아야 합니다. 점포를 먼저 계약했다가 시설 기준을 맞추지 못하는 일이 생기지 않도록, ${short} 후보 점포도 계약 전에 확인이 필요합니다.`,
      `점포 계약 뒤에 동물판매업 허가 기준을 맞추지 못하면 처음부터 다시 시작해야 합니다. ${BRAND} 가맹은 그래서 ${short} 점포 계약보다 인허가 점검을 먼저 둡니다.`,
    ]] },
    { id: 'roles', h: [`본사가 맡는 것, 점주가 하는 것`, `${short} 가맹점의 역할 나누기`, `${BRAND} 본사와 ${short} 점주의 역할`], p: [[
      `${BRAND} 가맹에서는 공급망, 건강·병력·혈통 정보 관리, 블로그·인스타그램·유튜브 마케팅, 인테리어 가이드, 상담·계약·사후관리 매뉴얼을 본사가 맡습니다. ${short} 점주님은 매장 운영과 고객 상담에 집중하면 됩니다.`,
      `개인이 만들기 어려운 부분은 본사가, 매장을 지키고 고객을 맞는 일은 점주님이 맡는 구조입니다. ${short} ${L}도 같은 방식으로 나눕니다.`,
    ], [
      `오픈 전에는 상담 교육, 고객 응대, 계약 진행, 사후관리까지 운영 전반을 교육하고, 오픈 뒤에도 정기 점검과 매월 프로모션 지원이 이어집니다. 창업 경험이 없는 분도 같은 순서로 따라올 수 있게 매뉴얼을 표준화했습니다.`,
      `교육은 오픈 전에 끝나지 않습니다. ${short} 매장을 연 뒤에도 정기 점검과 월별 프로모션으로 운영을 함께 챙기고, 점주님 의견은 정기 소통으로 운영에 반영합니다.`,
    ]] },
    { id: 'area', h: [`${short} 입지는 어떻게 고르나`, `상권이 겹치지 않게`, `${short} 점포 자리 찾기`], p: [[
      `${BRAND}은 무분별하게 매장을 늘리지 않습니다. 입지 분석으로 동일 상권 안 중복 가맹을 막아, 한 매장이 안정적으로 운영될 수 있는 환경을 먼저 만듭니다.`,
      `가맹점끼리 손님을 나눠 갖지 않도록 ${short}에서도 기존 점주와 겹치지 않는 자리를 찾는 것이 원칙입니다.`,
    ], [
      branch ? `${short}에는 이미 ${BRAND} ${branch}이 있어, ${branch} 상권과 겹치지 않는 입지부터 검토합니다.` : `${short} 후보 상권은 상담 단계에서 함께 보고, 다른 가맹점과의 거리와 상권 범위를 확인한 뒤 자리를 정합니다.`,
      `점포는 상권 분석과 인허가 점검을 거친 뒤 계약합니다. ${short} 후보 점포가 여러 곳이면 조건을 하나씩 비교해 결정합니다.`,
    ]] },
    { id: 'steps', h: [`오픈까지는 이렇게 진행됩니다`, `${short} ${L}, 상담부터 오픈까지`, `11단계를 네 구간으로 보면`], p: [[
      `처음은 상담입니다. 전화나 온라인으로 미팅을 예약하고, 본사 매장에서 궁금한 점을 묻고 운영 시스템을 직접 본 뒤 가맹 신청을 합니다.`,
      `${short}에서 오시는 분도 첫 단계는 같습니다. 미팅을 예약해 본사 매장을 둘러보고, 상담을 거친 뒤 가맹 신청 여부를 정합니다.`,
    ], [
      `그다음은 점포입니다. 상권 분석과 점포 개발, 인허가 점검, 점포 계약, 실측·도면 협의 순서로 진행하고, 가맹 계약 체결 뒤 인테리어 공사에 들어갑니다. 마지막으로 점주 교육을 마치면 ${short} 매장을 엽니다.`,
      `상권 분석 → 인허가 점검 → 점포 계약 → 실측·도면 협의 → 가맹 계약 → 인테리어 → 점주 교육을 거쳐 오픈합니다. 단계마다 본사가 함께 확인하므로 ${short}에서도 순서를 놓치지 않습니다.`,
    ]] },
    { id: 'after', h: [`오픈한 뒤에는`, `${short} 매장을 연 다음`, `문을 연 뒤가 더 중요합니다`], p: [[
      `${L}은 문을 연 다음이 더 중요합니다. ${BRAND}은 오픈 후 정기 점검과 매월 프로모션을 지원하고, 온라인 홍보는 본사가 블로그·인스타그램·유튜브로 직접 기획·운영합니다.`,
      `오픈 뒤 ${short} 매장의 온라인 홍보는 본사가 맡습니다. 점주님은 매장을 찾은 고객의 상담과 분양 뒤 관리에 집중합니다.`,
    ], [
      `'${FR_MOTTO}'는 것이 ${BRAND}의 운영 철학입니다. 점주님이 투자한 시간과 비용이 목표한 성과로 이어지도록 끝까지 함께합니다.`,
      `본사와 점주님은 단순한 가맹 관계가 아니라 함께 성장하는 파트너입니다. ${short} 점주님의 운영 의견도 꾸준한 소통으로 반영합니다.`,
    ]] },
  ];
  const close: Sec = { id: 'ready', h: [`상담 전에 준비하면 좋은 것`, `${short} 상담 예약 전 체크`, `본사 미팅 전에 정리할 것`], p: [[
    `창업은 적지 않은 자금이 드는 결정이라 ${BRAND}은 전화만으로 정하지 않고 본사 방문 상담을 권합니다. 퇴직금처럼 소중한 자금으로 준비한다면 더 신중하게 운영 시스템과 매장 환경을 직접 확인하세요.`,
    `${short}에서 오시더라도 전화로만 결정하지 않기를 권합니다. 본사 매장에서 운영 방식을 직접 보고, 충분히 상담한 뒤 판단하는 것이 맞습니다.`,
  ], [
    `상담 전에는 ${short} 안에서 생각해 둔 후보 지역, 원하는 점포 크기, 매장을 지킬 수 있는 시간을 정리해 오시면 좋습니다. 비용은 점포 크기·입지·인테리어 범위에 따라 달라 상담에서 항목별로 안내합니다. 미팅 예약은 ${CONTACT.phone}입니다.`,
    `후보 지역과 점포 조건, 운영 가능한 시간을 미리 정리해 오시면 상담이 빨라집니다. 창업 비용은 조건마다 달라 본사 상담에서 하나씩 나눠 안내합니다. 미팅 예약 ${CONTACT.phone}.`,
  ]] };

  // 유형마다 강조 순서가 다르고, 표기만 다른 페이지(짧은 표기)는 가운데 세 단락이 달라진다
  const ORDER: Record<FrWord, string[]> = {
    창업: ['why', 'hard', 'roles', 'steps', 'after', 'area'], 소자본창업: ['why', 'roles', 'hard', 'after', 'area', 'steps'],
    강아지분양창업: ['why', 'hard', 'roles', 'area', 'steps', 'after'], 애견분양창업: ['why', 'roles', 'hard', 'steps', 'after', 'area'],
    펫샵창업: ['why', 'area', 'roles', 'after', 'hard', 'steps'], 애견샵창업: ['why', 'area', 'steps', 'after', 'roles', 'hard'],
    애견분양샵창업: ['why', 'hard', 'after', 'roles', 'area', 'steps'], core: ['why', 'hard', 'roles', 'steps', 'area', 'after'],
  };
  const order = ORDER[word];
  const mid = breakdown ? order.slice(2, 5) : order.slice(1, 4);
  const pickSecs = [order[0], ...rotate(mid, s, 'ar')].map((id) => SECS.find((x) => x.id === id)!).concat(close);
  return {
    heading: pick([`${short} ${L} 안내`, `${short}에서 ${BRAND}과 ${L}`, `${short} ${L}, 알아 둘 것`], s, 'ah'),
    sections: pickSecs.map((x) => ({ h: pick(x.h, s, `h${x.id}`), p: x.p.map((v, i) => pick(v, s, `p${x.id}${i}`)) })),
  };
}
